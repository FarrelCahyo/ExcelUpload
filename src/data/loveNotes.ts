/**
 * Mendapatkan catatan cinta harian secara deterministik berdasarkan tanggal ISO (YYYY-MM-DD).
 * Pada tanggal yang sama, catatan yang dikembalikan selalu konsisten.
 */
export function getDailyLoveNote(dateISO?: string): LoveNote {
  if (LOVE_NOTES.length === 0) {
    return { id: 1, message: '' };
  }

  let targetDate = dateISO;
  if (!targetDate) {
    const today = new Date();
    const y = today.getFullYear();
    const m = String(today.getMonth() + 1).padStart(2, '0');
    const d = String(today.getDate()).padStart(2, '0');
    targetDate = `${y}-${m}-${d}`;
  }

  const parts = targetDate.split('-');
  let seed = 0;
  if (parts.length === 3) {
    const year = parseInt(parts[0], 10) || 2026;
    const month = parseInt(parts[1], 10) || 1;
    const day = parseInt(parts[2], 10) || 1;
    seed = year * 367 + month * 31 + day;
  } else {
    for (let i = 0; i < targetDate.length; i++) {
      seed = (seed * 31 + targetDate.charCodeAt(i)) >>> 0;
    }
  }

  const index = Math.abs(seed) % LOVE_NOTES.length;
  return {
    id: index + 1,
    message: LOVE_NOTES[index],
  };
}

/**
 * Mendapatkan satu catatan cinta secara acak dari katalog 50 pesan.
 * Opsi excludeId mencegah pengembalian id yang sama berturut-turut.
 */
export function getRandomLoveNote(excludeId?: number): LoveNote {
  const total = LOVE_NOTES.length;
  if (total === 0) {
    return { id: 1, message: '' };
  }

  const candidateIndices: number[] = [];
  for (let i = 0; i < total; i++) {
    if (excludeId === undefined || i + 1 !== excludeId) {
      candidateIndices.push(i);
    }
  }

  if (candidateIndices.length === 0) {
    return { id: 1, message: LOVE_NOTES[0] };
  }

  const pickedIndex = candidateIndices[Math.floor(Math.random() * candidateIndices.length)];
  return {
    id: pickedIndex + 1,
    message: LOVE_NOTES[pickedIndex],
  };
}
